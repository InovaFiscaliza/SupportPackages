classdef DownloadPanel < handle

    % DOWNLOADPANEL Reusable asynchronous download queue UI.
    %
    % DownloadPanel owns the presentation and lifecycle of multiple download
    % rows: the download avatar, the popup panel, progress aggregation,
    % pause/resume/stop controls, conflict decisions, and cleanup of UI and
    % downloader handles. It deliberately does not know how authentication
    % or network transfer is implemented.
    %
    % The caller supplies DownloaderFactory. The factory receives a normalized
    % request containing the URL, temporary and target folders, file name,
    % task-scoped staging paths, and conflict actions. It must return an
    % object exposing start, pause, resume, stop, ProgressFcn, CompletedFcn,
    % and ErrorFcn.
    %
    % Temporary files are written below TempPath. Completed files are written
    % below TargetPath. Existing target and partial-file conflicts are shown
    % in the download row instead of being handled by modal dialogs.

    properties
        executionMode (1,:) char = 'MATLABEnvironment'
        TempPath (1,:) char = ''
        TargetPath (1,:) char = ''
        CollisionPolicy (1,:) char = 'askInRow'
        PartialConflictPolicy (1,:) char = 'askInRow'
        CompletedFcn = []
        ErrorFcn = []
    end

    properties (SetAccess = private)
        AvatarHTML
        DownloaderFactory
    end

    properties (Access = private)
        ParentContainer
        UIFigure
        DownloadDialog
        DownloadHeader
        DownloadTitleLabel
        CloseImage
        DownloadContent
        DownloadStack
        DownloadTasks = {}
        NextDownloadID (1,1) double = 0
        AvatarHTMLReady (1,1) logical = false
        AvatarState struct = struct('level', 0, ...
                                    'inProgress', false, ...
                                    'ballCount', 0, ...
                                    'speedRadiansPerSecond', 0)
        OriginalWindowButtonDownFcn = []
        IsDeleting (1,1) logical = false
    end


    methods
        %-----------------------------------------------------------------%
        function obj = DownloadPanel(parentContainer, options)
            % DOWNLOADPANEL Construct a download panel attached to a UI parent.
            %
            % PARENTCONTAINER is a UI container belonging to a figure.
            % DOWNLOADERFACTORY is a function handle that creates one
            % downloader object from the normalized request generated by the
            % panel. Optional name-value arguments configure execution mode,
            % temporary and target folders, and conflict policies.
            arguments
                parentContainer
                options.DownloaderFactory (1,1) function_handle
                options.executionMode (1,:) char = 'MATLABEnvironment'
                options.tempPath (1,:) char = tempdir
                options.targetPath (1,:) char = ''
                options.CollisionPolicy (1,:) char = 'askInRow'
                options.PartialConflictPolicy (1,:) char = 'askInRow'
            end

            obj.ParentContainer = parentContainer;
            obj.UIFigure = findFigure(parentContainer);
            if isempty(obj.UIFigure) || ~isvalid(obj.UIFigure)
                error('ui:DownloadPanel:invalidParent', ...
                      'The parent container must belong to a valid figure.')
            end

            obj.DownloaderFactory = options.DownloaderFactory;
            obj.executionMode = options.executionMode;
            obj.TempPath = char(options.tempPath);
            obj.TargetPath = char(options.targetPath);
            obj.CollisionPolicy = options.CollisionPolicy;
            obj.PartialConflictPolicy = options.PartialConflictPolicy;

            obj.AvatarHTML = uihtml(parentContainer);
            obj.AvatarHTML.HTMLSource = avatarHTMLPath();
            obj.AvatarHTML.HTMLEventReceivedFcn = @(~, event) obj.onAvatarEvent(event);

            obj.OriginalWindowButtonDownFcn = obj.UIFigure.WindowButtonDownFcn;
            obj.UIFigure.WindowButtonDownFcn = @(source, event) obj.onFigureButtonDown(source, event);
        end

        %-----------------------------------------------------------------%
        function delete(obj)
            % DELETE Stop active downloads and release panel-owned UI handles.
            if obj.IsDeleting
                return
            end
            obj.IsDeleting = true;

            for taskID = 1:numel(obj.DownloadTasks)
                task = obj.DownloadTasks{taskID};
                if isempty(task)
                    continue
                end
                obj.stopAndReleaseDownloader(task)
                obj.deleteTaskGraphics(task)
            end
            obj.DownloadTasks = {};
            obj.closeDownloadContainer()

            if ~isempty(obj.AvatarHTML) && isvalid(obj.AvatarHTML)
                delete(obj.AvatarHTML)
            end
            if ~isempty(obj.UIFigure) && isvalid(obj.UIFigure)
                obj.UIFigure.WindowButtonDownFcn = obj.OriginalWindowButtonDownFcn;
            end
        end

        %-----------------------------------------------------------------%
        function taskID = addDownload(obj, url)
            % ADDDOWNLOAD Add and start a download for a URL.
            %
            % The file name is derived from URL. Depending on executionMode,
            % the target is resolved directly or through a file-selection
            % dialog. The method returns the numeric task identifier, or an
            % empty value when the user cancels destination selection.
            arguments
                obj
                url (1,:) char {mustBeNonempty}
            end

            url = char(url);
            [finalPath, cancelled] = obj.resolveFinalPath(url);
            if cancelled
                taskID = [];
                return
            end

            [targetFolder, fileName, extension] = fileparts(finalPath);
            fileName = [fileName, extension];
            taskID = obj.createTask(url, targetFolder, fileName, finalPath);
            task = obj.getTask(taskID);
            existingPartialPath = findPartialPath(task.TempFolder, task.FileName);
            if ~isempty(existingPartialPath)
                task.PartialPath = existingPartialPath;
                task.ChunkPath = [existingPartialPath, '.chunk'];
            end
            obj.DownloadTasks{taskID} = task;

            if pathExists(finalPath)
                obj.configureTargetConflict(taskID)
            elseif ~isempty(existingPartialPath)
                obj.configurePartialConflict(taskID)
            else
                obj.startTask(taskID, 'none', 'none')
            end
        end

        %-----------------------------------------------------------------%
        function show(obj)
            % SHOW Make the download popup visible and bring it to the front.
            if isempty(obj.DownloadDialog) || ~isvalid(obj.DownloadDialog)
                return
            end
            obj.DownloadDialog.Visible = 'on';
            drawnow
            obj.positionDownloadContainer()
            uistack(obj.DownloadDialog, 'top')
        end

        %-----------------------------------------------------------------%
        function hide(obj)
            % HIDE Hide the download popup without stopping its downloads.
            if ~isempty(obj.DownloadDialog) && isvalid(obj.DownloadDialog)
                obj.DownloadDialog.Visible = 'off';
            end
        end

        %-----------------------------------------------------------------%
        function stop(obj, taskID)
            % STOP Stop and remove one download task.
            %
            % The task's partial and chunk files are retained so a later
            % addDownload call can offer resume or restart.
            task = obj.getTask(taskID);
            if isempty(task)
                return
            end

            task.IsStopped = true;
            task.LifecycleState = 'stopped';
            obj.DownloadTasks{taskID} = task;
            obj.stopAndReleaseDownloader(task)
            restoreBackup(task)
            obj.removeTask(taskID)
        end

        %-----------------------------------------------------------------%
        function stopAll(obj)
            % STOPALL Stop and remove every download task in the panel.
            for taskID = 1:numel(obj.DownloadTasks)
                if ~isempty(obj.DownloadTasks{taskID})
                    obj.stop(taskID)
                end
            end
        end

        %-----------------------------------------------------------------%
        function tf = isActive(obj, filePath)
            % ISACTIVE Return true when a task targets filePath.
            tf = false;
            for taskID = 1:numel(obj.DownloadTasks)
                task = obj.DownloadTasks{taskID};
                if isempty(task) || task.IsStopped
                    continue
                end
                if strcmpi(task.FinalPath, filePath)
                    tf = true;
                    return
                end
            end
        end
    end


    % Private implementation: HTML events, task state, row controls, layout,
    % conflict handling, and aggregate avatar updates.
    methods (Access = private)
        %-----------------------------------------------------------------%
        function onAvatarEvent(obj, event)
            eventName = eventProperty(event, {'HTMLEventName', 'EventName'});
            payload = eventProperty(event, {'HTMLEventData', 'Data'});
            if ischar(payload) || (isstring(payload) && isscalar(payload))
                try
                    payload = jsondecode(char(payload));
                catch
                    payload = struct();
                end
            end

            if strcmp(eventName, 'downloadAvatarReady') || ...
                    (isstruct(payload) && isfield(payload, 'type') && strcmp(string(payload.type), 'ready'))
                obj.AvatarHTMLReady = true;
                obj.AvatarHTML.Data = obj.AvatarState;
                return
            end

            if strcmp(eventName, 'downloadAvatarClick') || ...
                    (isstruct(payload) && isfield(payload, 'type') && strcmp(string(payload.type), 'click'))
                obj.show()
            end
        end

        %-----------------------------------------------------------------%
        function onFigureButtonDown(obj, source, event)
            if ~isempty(obj.DownloadDialog) && isvalid(obj.DownloadDialog) && ...
                    strcmp(obj.DownloadDialog.Visible, 'on')
                point = obj.UIFigure.CurrentPoint;
                panelPosition = obj.DownloadDialog.Position;
                insidePanel = point(1) >= panelPosition(1) && ...
                              point(1) <= panelPosition(1) + panelPosition(3) && ...
                              point(2) >= panelPosition(2) && ...
                              point(2) <= panelPosition(2) + panelPosition(4);
                if ~insidePanel
                    obj.hide()
                end
            end
            invokeCallback(obj.OriginalWindowButtonDownFcn, source, event)
        end

