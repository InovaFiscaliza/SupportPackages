        %-----------------------------------------------------------------%
        function resolveConflict(obj, taskID, action)
            task = obj.getTask(taskID);
            if isempty(task) || ~strcmp(task.LifecycleState, 'awaitingConflictDecision')
                return
            end
            wasTargetConflict = strcmp(task.ConflictType, 'target');

            if strcmp(action, 'cancel')
                obj.stop(taskID)
                return
            end

            if strcmp(task.ConflictType, 'target') && strcmp(action, 'overwrite')
                task.BackupPath = fullfile(task.TempFolder, [task.TaskID, '_backup_', task.FileName]);
                try
                    ensureFolder(task.TempFolder)
                    moveFileWithFallback(task.FinalPath, task.BackupPath)
                catch exception
                    obj.onDownloadError(taskID, exception)
                    return
                end
                task.CollisionAction = 'overwrite';
            elseif strcmp(task.ConflictType, 'target') && strcmp(action, 'uniqueName')
                task.FinalPath = uniqueTargetPath(task.FinalPath);
                [task.TargetFolder, baseName, extension] = fileparts(task.FinalPath);
                task.FileName = [baseName, extension];
                task.StatusLabel.Text = task.FileName;
                task.PartialPath = fullfile(task.TempFolder, [task.TaskID, '_', task.FileName, '.part']);
                task.ChunkPath = [task.PartialPath, '.chunk'];
                task.CollisionAction = 'uniqueName';
            elseif strcmp(task.ConflictType, 'partial') && strcmp(action, 'restart')
                deleteIfExists(task.PartialPath)
                deleteIfExists(task.ChunkPath)
                task.PartialPath = fullfile(task.TempFolder, [task.TaskID, '_', task.FileName, '.part']);
                task.ChunkPath = [task.PartialPath, '.chunk'];
                task.PartialAction = 'restart';
            elseif strcmp(task.ConflictType, 'partial') && strcmp(action, 'resume')
                task.PartialAction = 'resume';
            end

            for buttonIndex = 1:numel(task.ConflictButtons)
                task.ConflictButtons(buttonIndex).Enable = 'off';
            end
            task.ConflictPanel.Visible = 'off';
            task.PauseButton.Visible = 'on';
            task.StopButton.Visible = 'on';
            task.GridLayout.RowHeight = {24, 20, 46, 30, 1};
            task.RowHeight = 154;
            task.ConflictType = '';
            obj.DownloadTasks{taskID} = task;
            obj.refreshDownloadContainer()
            if wasTargetConflict && ~isempty(task.PartialPath) && isfile(task.PartialPath)
                obj.configurePartialConflict(taskID)
                return
            end
            obj.startTask(taskID, task.CollisionAction, task.PartialAction)
        end

        %-----------------------------------------------------------------%
        function startTask(obj, taskID, collisionAction, partialAction)
            task = obj.getTask(taskID);
            if isempty(task) || task.IsStopped
                return
            end

            try
                ensureFolder(task.TempFolder)
                task.Request = struct('URL', task.URL, ...
                                      'TaskID', task.TaskID, ...
                                      'TempFolder', task.TempFolder, ...
                                      'TargetFolder', task.TargetFolder, ...
                                      'FileName', task.FileName, ...
                                      'FinalPath', task.FinalPath, ...
                                      'PartialPath', task.PartialPath, ...
                                      'ChunkPath', task.ChunkPath, ...
                                      'BackupPath', task.BackupPath, ...
                                      'CollisionAction', collisionAction, ...
                                      'PartialAction', partialAction);
                downloader = obj.DownloaderFactory(task.Request);
                validateDownloader(downloader)
                task.Downloader = downloader;
                task.LifecycleState = 'active';
                task.IsPaused = false;
                obj.DownloadTasks{taskID} = task;

                downloader.ProgressFcn = @(receivedBytes, totalBytes) obj.onDownloadProgress(taskID, receivedBytes, totalBytes);
                downloader.CompletedFcn = @(info) obj.onDownloadCompleted(taskID, info);
                downloader.ErrorFcn = @(exception) obj.onDownloadError(taskID, exception);
                obj.refreshDownloadContainer()
                obj.updateDownloadAvatar()
                start(downloader)
            catch exception
                obj.onDownloadError(taskID, exception)
            end
        end

        %-----------------------------------------------------------------%
        function togglePause(obj, taskID)
            task = obj.getTask(taskID);
            if isempty(task) || ~ismember(task.LifecycleState, {'active', 'paused'}) || ...
                    isempty(task.Downloader)
                return
            end

            if task.IsPaused
                resume(task.Downloader)
                task.IsPaused = false;
                task.LifecycleState = 'active';
                task.PauseButton.Text = 'Pause';
            else
                pause(task.Downloader)
                task.IsPaused = true;
                task.LifecycleState = 'paused';
                task.PauseButton.Text = 'Resume';
            end
            task.TransferRate = NaN;
            obj.DownloadTasks{taskID} = task;
            obj.updateDownloadAvatar()
        end

        %-----------------------------------------------------------------%
        function onDownloadProgress(obj, taskID, receivedBytes, totalBytes)
            task = obj.getTask(taskID);
            if isempty(task) || ~strcmp(task.LifecycleState, 'active') || obj.IsDeleting
                return
            end

            receivedBytes = double(receivedBytes);
            if isempty(totalBytes)
                totalBytes = [];
            else
                totalBytes = double(totalBytes);
            end
            task.ReceivedBytes = receivedBytes;
            task.TotalBytes = totalBytes;

            elapsedSeconds = toc(task.StartTimer);
            task.ProgressSamples(end+1, :) = [elapsedSeconds, receivedBytes];
            cutoffTime = elapsedSeconds - 10;
            samplesBeforeCutoff = find(task.ProgressSamples(:, 1) <= cutoffTime, 1, 'last');
            if ~isempty(samplesBeforeCutoff)
                task.ProgressSamples = task.ProgressSamples(samplesBeforeCutoff:end, :);
            end

            transferRate = 100000;
            if elapsedSeconds >= 10 && size(task.ProgressSamples, 1) >= 2
                sampleDuration = task.ProgressSamples(end, 1) - task.ProgressSamples(1, 1);
                if sampleDuration >= 10
                    transferRate = (task.ProgressSamples(end, 2) - task.ProgressSamples(1, 2)) / sampleDuration;
                end
            end

            if isempty(totalBytes) || totalBytes <= 0
                fraction = 0;
            else
                fraction = min(receivedBytes / totalBytes, 1);
            end
            task.ProgressFraction = fraction;
            task.TransferRate = transferRate;
            task.BytesLabel.Text = progressText(receivedBytes, totalBytes, elapsedSeconds, transferRate);
            obj.updateProgressScale(task)
            obj.DownloadTasks{taskID} = task;
            obj.updateDownloadAvatar()
            drawnow limitrate
        end

        %-----------------------------------------------------------------%
        function onDownloadCompleted(obj, taskID, info)
            task = obj.getTask(taskID);
            if isempty(task) || task.IsStopped
                return
            end

            if ~isstruct(info)
                info = struct('FinalPath', task.FinalPath, 'BytesReceived', task.ReceivedBytes, 'TotalBytes', task.TotalBytes);
            elseif ~isfield(info, 'FinalPath') || isempty(info.FinalPath)
                info.FinalPath = task.FinalPath;
            end
            taskInfo = publicTaskInfo(task);
            taskInfo.FinalPath = info.FinalPath;
            obj.removeTask(taskID)
            invokeCallback(obj.CompletedFcn, taskID, info, taskInfo)
        end

        %-----------------------------------------------------------------%
        function onDownloadError(obj, taskID, exception)
            task = obj.getTask(taskID);
            if isempty(task) || task.IsStopped
                return
            end
            taskInfo = publicTaskInfo(task);
            restoreBackup(task)
            obj.removeTask(taskID)
            invokeCallback(obj.ErrorFcn, taskID, exception, taskInfo)
        end

        %-----------------------------------------------------------------%
        function removeTask(obj, taskID)
            task = obj.getTask(taskID);
            if isempty(task)
                return
            end
            obj.stopAndReleaseDownloader(task)
            obj.deleteTaskGraphics(task)
            obj.DownloadTasks{taskID} = [];
            obj.refreshDownloadContainer()
            obj.updateDownloadAvatar()
        end

        %-----------------------------------------------------------------%
        function task = getTask(obj, taskID)
            task = [];
            if ~isscalar(taskID) || taskID < 1 || taskID > numel(obj.DownloadTasks)
                return
            end
            task = obj.DownloadTasks{taskID};
            if isempty(task)
                task = [];
            end
        end

        %-----------------------------------------------------------------%
        function stopAndReleaseDownloader(~, task)
            downloader = task.Downloader;
            if isempty(downloader)
                return
            end
            try
                if isprop(downloader, 'ProgressFcn')
                    downloader.ProgressFcn = [];
                end
                if isprop(downloader, 'CompletedFcn')
                    downloader.CompletedFcn = [];
                end
                if isprop(downloader, 'ErrorFcn')
                    downloader.ErrorFcn = [];
                end
            catch
            end
            try
                if ismethod(downloader, 'stop')
                    stop(downloader)
                end
            catch
            end
            try
                if ismethod(downloader, 'delete')
                    delete(downloader)
                end
            catch
            end
        end

        %-----------------------------------------------------------------%
        function deleteTaskGraphics(~, task)
            handles = {task.Dialog, task.Separator};
            for handleIndex = 1:numel(handles)
                handle = handles{handleIndex};
                try
                    if ~isempty(handle) && isvalid(handle)
                        delete(handle)
                    end
                catch
                end
            end
        end

        %-----------------------------------------------------------------%
        function ensureDownloadContainer(obj)
            if ~isempty(obj.DownloadDialog) && isvalid(obj.DownloadDialog)
                return
            end

            obj.DownloadDialog = uipanel(obj.UIFigure, ...
                                         'Title', '', ...
                                         'Visible', 'off', ...
                                         'Scrollable', 'off', ...
                                         'Units', 'pixels', ...
                                         'BorderType', 'line', ...
                                         'BackgroundColor', obj.UIFigure.Color);
            obj.DownloadHeader = uipanel(obj.DownloadDialog, ...
                                         'BorderType', 'none', ...
                                         'BackgroundColor', obj.UIFigure.Color);
            obj.DownloadTitleLabel = uilabel(obj.DownloadHeader, ...
                                             'Text', 'Downloads', ...
                                             'FontWeight', 'bold', ...
                                             'HorizontalAlignment', 'left', ...
                                             'VerticalAlignment', 'center');
            obj.CloseImage = uiimage(obj.DownloadHeader, ...
                                     'ImageSource', closeIconPath(), ...
                                     'ImageClickedFcn', @(~, ~) obj.hide());
            obj.DownloadContent = uipanel(obj.DownloadDialog, ...
                                          'BorderType', 'none', ...
                                          'Units', 'pixels', ...
                                          'BackgroundColor', obj.UIFigure.Color);
            obj.DownloadStack = uigridlayout(obj.DownloadContent, [1, 1]);
            obj.DownloadStack.Padding = [0, 0, 0, 0];
            obj.DownloadStack.RowSpacing = 0;
            obj.DownloadStack.ColumnWidth = {'1x'};
            obj.DownloadStack.RowHeight = {154};
            obj.positionDownloadContainer()
        end

        %-----------------------------------------------------------------%
        function closeDownloadContainer(obj)
            if ~isempty(obj.DownloadDialog) && isvalid(obj.DownloadDialog)
                delete(obj.DownloadDialog)
            end
            obj.DownloadDialog = [];
            obj.DownloadContent = [];
            obj.DownloadStack = [];
        end

        %-----------------------------------------------------------------%
        function refreshDownloadContainer(obj)
            if isempty(obj.DownloadDialog) || ~isvalid(obj.DownloadDialog)
                return
            end

            activeIDs = [];
            for taskID = 1:numel(obj.DownloadTasks)
                task = obj.DownloadTasks{taskID};
                if ~isempty(task) && ~isempty(task.Dialog) && isvalid(task.Dialog)
                    activeIDs(end+1) = taskID;
                end
            end

            if isempty(activeIDs)
                obj.closeDownloadContainer()
                return
            end

            activeIDs = fliplr(activeIDs);
            rowHeights = repmat({1}, 1, 2*numel(activeIDs));
            for row = 1:numel(activeIDs)
                task = obj.DownloadTasks{activeIDs(row)};
                rowHeights{2*row - 1} = task.RowHeight;
                task.Dialog.Layout.Row = 2*row - 1;
                task.Dialog.Layout.Column = 1;
                task.Separator.Layout.Row = 2*row;
                task.Separator.Layout.Column = 1;
                task.Separator.Visible = ternary(row < numel(activeIDs), 'on', 'off');
            end
            obj.DownloadStack.RowHeight = rowHeights;
            obj.positionDownloadContainer()
            obj.resizeDownloadProgressBars()
        end

        %-----------------------------------------------------------------%
        function positionDownloadContainer(obj)
            if isempty(obj.DownloadDialog) || ~isvalid(obj.DownloadDialog) || ...
                    isempty(obj.AvatarHTML) || ~isvalid(obj.AvatarHTML)
                return
            end

            drawnow limitrate
            avatarPosition = getpixelposition(obj.AvatarHTML, true);
            figurePosition = obj.UIFigure.Position;
            figureWidth = figurePosition(3);
            figureHeight = figurePosition(4);
            panelWidth = min(560, max(220, figureWidth - 16));
            headerHeight = 24;
            borderInset = 2;
            panelGap = 12;
            activeHeight = 0;
            for taskID = 1:numel(obj.DownloadTasks)
                task = obj.DownloadTasks{taskID};
                if ~isempty(task)
                    activeHeight = activeHeight + task.RowHeight + 1;
                end
            end
            contentHeight = max(1, activeHeight);
            requiredPanelHeight = contentHeight + headerHeight + 2 * borderInset;
            availablePanelHeight = min(avatarPosition(2) - panelGap - 8, figureHeight - 16);
            panelHeight = min(max(64, requiredPanelHeight), max(64, availablePanelHeight));
            panelX = min(max(8, avatarPosition(1)), max(8, figureWidth - panelWidth - 8));
            panelY = avatarPosition(2) - panelHeight - panelGap;
            panelY = min(max(8, panelY), max(8, figureHeight - panelHeight - 8));

            obj.DownloadDialog.Position = [panelX, panelY, panelWidth, panelHeight];
            innerPosition = obj.DownloadDialog.InnerPosition;
            needsVerticalScroll = contentHeight > innerPosition(4);
            obj.DownloadDialog.Scrollable = ternary(needsVerticalScroll, 'on', 'off');
            drawnow limitrate
            innerPosition = obj.DownloadDialog.InnerPosition;
            contentWidth = max(1, floor(innerPosition(3)) - 16 - 2 * borderInset);
            obj.DownloadContent.Position = [borderInset, borderInset, contentWidth, contentHeight];
            obj.DownloadHeader.Position = [borderInset, contentHeight + borderInset, contentWidth, headerHeight];
            obj.DownloadTitleLabel.Position = [8, 0, max(1, contentWidth - 32), headerHeight];
            closeIconSize = 16;
            closeIconMargin = 4;
            obj.CloseImage.Position = [max(closeIconMargin, contentWidth - closeIconSize - closeIconMargin), ...
                                       max(closeIconMargin, (headerHeight - closeIconSize) / 2), ...
                                       closeIconSize, closeIconSize];
        end

        %-----------------------------------------------------------------%
        function resizeDownloadProgressBars(obj)
            for taskID = 1:numel(obj.DownloadTasks)
                task = obj.DownloadTasks{taskID};
                if isempty(task) || isempty(task.ProgressTrack) || ~isvalid(task.ProgressTrack)
                    continue
                end
                obj.updateProgressScale(task)
            end
        end

        %-----------------------------------------------------------------%
        function updateProgressScale(~, task)
            if isempty(task.ProgressTrack) || ~isvalid(task.ProgressTrack)
                return
            end
            trackSize = task.ProgressTrack.InnerPosition;
            trackWidth = max(0, trackSize(3));
            trackHeight = max(1, trackSize(4));
            task.ProgressFill.Position = [0, 0, task.ProgressFraction * trackWidth, trackHeight];
            markerWidth = 1;
            markerXPositions = round((0:4) / 4 * max(0, trackWidth - markerWidth));
            for markerIndex = 1:numel(task.ProgressMarkers)
                marker = task.ProgressMarkers(markerIndex);
                if ~isempty(marker) && isvalid(marker)
                    marker.Position = [markerXPositions(markerIndex), 0, markerWidth, trackHeight];
                end
            end
        end

        %-----------------------------------------------------------------%
        function updateDownloadAvatar(obj)
            activeCount = 0;
            receivedBytes = 0;
            totalBytes = 0;
            transferRate = 0;

            for taskID = 1:numel(obj.DownloadTasks)
                task = obj.DownloadTasks{taskID};
                if isempty(task) || ~strcmp(task.LifecycleState, 'active')
                    continue
                end
                activeCount = activeCount + 1;
                if isfinite(task.ReceivedBytes)
                    receivedBytes = receivedBytes + max(0, double(task.ReceivedBytes));
                end
                if ~isempty(task.TotalBytes) && isfinite(task.TotalBytes) && task.TotalBytes > 0
                    totalBytes = totalBytes + double(task.TotalBytes);
                end
                if isfinite(task.TransferRate) && task.TransferRate > 0
                    transferRate = transferRate + double(task.TransferRate);
                end
            end

            percentage = 0;
            if totalBytes > 0
                percentage = min(100, receivedBytes / totalBytes * 100);
            end
            state = struct('level', avatarLevel(percentage), ...
                           'inProgress', activeCount > 0, ...
                           'ballCount', activeCount, ...
                           'speedRadiansPerSecond', transferRate / 1024^2 * 2 * pi);
            if isequal(state, obj.AvatarState)
                return
            end
            obj.AvatarState = state;
            if obj.AvatarHTMLReady && ~isempty(obj.AvatarHTML) && isvalid(obj.AvatarHTML)
                obj.AvatarHTML.Data = state;
            end
        end
    end


    methods (Access = private)
        %-----------------------------------------------------------------%
        function [finalPath, cancelled] = resolveFinalPath(obj, url)
            cancelled = false;
            fileName = filenameFromURL(url);
            if strcmp(obj.executionMode, 'webApp')
                if isempty(strtrim(obj.TargetPath)) || ~isfolder(obj.TargetPath)
                    error('ui:DownloadPanel:missingTargetPath', ...
                          'TargetPath must be an existing folder in webApp mode.')
                end
                finalPath = fullfile(obj.TargetPath, fileName);
                return
            end

            defaultName = fileName;
            if ~isempty(strtrim(obj.TargetPath))
                defaultName = fullfile(obj.TargetPath, fileName);
            end
            [selectedName, selectedFolder] = uiputfile('*.*', '', defaultName);
            if isequal(selectedName, 0)
                finalPath = '';
                cancelled = true;
                return
            end
            figure(obj.UIFigure)
            finalPath = fullfile(selectedFolder, selectedName);
        end
    end


